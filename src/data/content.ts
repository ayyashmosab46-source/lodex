export interface ClueItem {
  id: string;
  clues: [string, string, string, string];
  answer: string;
  aliases: string[];
  theme: string;
  hint: string;
  options?: string[];
}

export interface DrawWordItem {
  id: string;
  word: string;
  aliases: string[];
  category: string;
  difficulty: 'easy' | 'medium' | 'hard';
}

export interface WhoAmIItem {
  id: string;
  characterName: string;
  aliases: string[];
  category: string;
  clues: [string, string, string]; // 3 progressive clues
  description: string;
  hint: string;
  options?: string[];
}

